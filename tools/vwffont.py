"""VWF font: font/<lang>.txt (pixel art) -> glyph data + widths for bank $92, and tbl/<lang>.tbl.

Code = $200 + n. ASCII characters use n = ord(c) (so '0' = $230, 'A' = $241); other glyphs (Vietnamese) are
given as "=0xNN" or get the next free n from $80 upward. Glyph rows: art row 0 -> cell row 2.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
NAMES = {"space": " "}
TOP = 2      # cell row of art row 0
SHADOW = 1   # colour of the drop shadow
INK = 3


def parse(path):
    """[(char, rows)] in file order."""
    glyphs, cur = [], None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") and cur is None or not line:
            continue
        if line.startswith("="):
            name = line[1:]
            cur = (NAMES.get(name, name), [])
            glyphs.append(cur)
            continue
        if line.startswith("#") and len(cur[1]) == 12:
            continue
        cur[1].append(line)
    for ch, rows in glyphs:
        assert len(rows) == 12, (ch, len(rows))
    return glyphs


def render(rows):
    """16x8 pixel values and advance width."""
    w = max(len(r.rstrip(".")) for r in rows) if any("#" in r for r in rows) else len(rows[0])
    px = [[0] * 8 for _ in range(16)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                assert x < 7, "glyph wider than 7 px"
                px[TOP + y][x] = INK
    for y in range(15, -1, -1):
        for x in range(7, -1, -1):
            if px[y][x] == 0 and x > 0 and y > 0 and px[y - 1][x - 1] == INK:
                px[y][x] = SHADOW
    return px, min(w + 1, 8)


def tile_bytes(px):
    out = bytearray()
    for y in range(16):
        p0 = p1 = 0
        for x in range(8):
            v = px[y][x]
            p0 |= (v & 1) << (7 - x)
            p1 |= (v >> 1) << (7 - x)
        out += bytes([p0, p1])
    return bytes(out)


def build(lang):
    """Returns (font bytes for n = 0..N-1, width bytes, {char: code})."""
    glyphs = parse(os.path.join(ROOT, "font", lang + ".txt"))
    codes, nxt = {}, 0x80
    for ch, _ in glyphs:
        if len(ch) == 1 and ord(ch) < 0x80:
            codes[ch] = ord(ch)
        elif ch.startswith("0x"):
            codes[ch] = int(ch, 16)
        else:
            codes[ch] = nxt
            nxt += 1
    n = max(codes.values()) + 1
    font, widths = bytearray(32 * n), bytearray(n)
    for ch, rows in glyphs:
        px, w = render(rows)
        i = codes[ch]
        font[i * 32:i * 32 + 32] = tile_bytes(px)
        widths[i] = w
    return bytes(font), bytes(widths), {ch: 0x200 + i for ch, i in codes.items()}


def write_tbl(lang):
    _, widths, codes = build(lang)
    path = os.path.join(ROOT, "tbl", lang + ".tbl")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by tools/vwffont.py from font/%s.txt: code=char ;width px\n" % lang)
        for ch, code in sorted(codes.items(), key=lambda kv: kv[1]):
            f.write("%03X=%s\n" % (code, "\\s" if ch == " " else ch))
    return path


def widths_by_char(lang):
    _, widths, codes = build(lang)
    return {ch: widths[code - 0x200] for ch, code in codes.items()}


if __name__ == "__main__":
    import sys
    print(write_tbl(sys.argv[1] if len(sys.argv) > 1 else "en"))
